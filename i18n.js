  function normalizeLocale(value) {
    return String(value || '').toLowerCase().startsWith('en') ? 'en' : DEFAULT_LOCALE;
  }
  let locale = normalizeLocale(localStorage.getItem(STORAGE_KEY) || DEFAULT_LOCALE);

  function t(key, vars = {}) {
    const table = translations[locale] || translations[DEFAULT_LOCALE];
    let value = table[key] ?? translations[DEFAULT_LOCALE][key] ?? key;
    return String(value).replace(/\{(\w+)\}/g, (_match, name) => vars[name] ?? '');
  }

  function applyStatic() {
    document.documentElement.lang = locale;
    document.querySelectorAll('[data-i18n]').forEach(node => {
      node.textContent = t(node.dataset.i18n);
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(node => {
      node.placeholder = t(node.dataset.i18nPlaceholder);
    });
    document.querySelectorAll('[data-i18n-aria]').forEach(node => {
      node.setAttribute('aria-label', t(node.dataset.i18nAria));
    });
    document.title = t('meta.title');
    document.querySelector('meta[name="description"]')?.setAttribute('content', t('meta.description'));
    document.querySelector('meta[property="og:title"]')?.setAttribute('content', t('meta.title'));
    document.querySelector('meta[property="og:description"]')?.setAttribute('content', t('meta.ogDescription'));
    const picker = document.querySelector('#language-select');
    if (picker) picker.value = locale;
    document.dispatchEvent(new CustomEvent('montapc:languagechange', { detail: { locale } }));
  }

  function setLocale(next) {
    locale = normalizeLocale(next);
    localStorage.setItem(STORAGE_KEY, locale);
    applyStatic();
  }

  window.MONTAPC_I18N = {
    t,
    setLocale,
    applyStatic,
    get locale() { return locale; },
    defaultLocale: DEFAULT_LOCALE
  };

  document.addEventListener('DOMContentLoaded', () => {
    document.querySelector('#language-select')?.addEventListener('change', event => setLocale(event.target.value));
    applyStatic();
  });
